#!/bin/bash

set -euo pipefail

PYTHON_BIN="${PYTHON:-python}"

MEMAGENT_BACKEND_MODEL="${MEMAGENT_BACKEND_MODEL:-BytedTsinghua-SIA/RL-MemoryAgent-7B}"
MEMAGENT_BACKEND_API_URL="${MEMAGENT_BACKEND_API_URL:-http://localhost:9002/v1/chat/completions}"
MEMAGENT_PROXY_HOST="${MEMAGENT_PROXY_HOST:-0.0.0.0}"
MEMAGENT_PROXY_PORT="${MEMAGENT_PROXY_PORT:-9001}"
MEMORY_CHUNK_SIZE="${MEMORY_CHUNK_SIZE:-5000}"
MEMAGENT_MAX_TOKENS="${MEMAGENT_MAX_TOKENS:-1536}"
MEMAGENT_TEMPERATURE="${MEMAGENT_TEMPERATURE:-0.0}"
MEMAGENT_FORCE_ITERATIVE="${MEMAGENT_FORCE_ITERATIVE:-true}"

echo "Using Python: $($PYTHON_BIN -c 'import sys; print(sys.executable)')"
echo "Starting memagent iterative proxy at ${MEMAGENT_PROXY_HOST}:${MEMAGENT_PROXY_PORT}"
echo "Backend model: ${MEMAGENT_BACKEND_MODEL}"
echo "Backend API: ${MEMAGENT_BACKEND_API_URL}"

export MEMAGENT_BACKEND_MODEL
export MEMAGENT_BACKEND_API_URL
export MEMAGENT_PROXY_HOST
export MEMAGENT_PROXY_PORT
export MEMORY_CHUNK_SIZE
export MEMAGENT_MAX_TOKENS
export MEMAGENT_TEMPERATURE
export MEMAGENT_FORCE_ITERATIVE

"$PYTHON_BIN" scripts/memagent_iterative_proxy.py
